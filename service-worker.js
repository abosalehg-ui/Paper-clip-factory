const CACHE_NAME = `paperclip-factory-${CACHE_VERSION}`;

// The app shell must be complete for the game to boot offline; media can be
// fetched on demand. Splitting them means one failed audio file no longer
// fails the whole install and leaves the player with no offline mode at all.
const isMedia = (path) => path.includes('/assets/');
const SHELL_ASSETS = ASSETS.filter((path) => !isMedia(path));
const MEDIA_ASSETS = ASSETS.filter(isMedia);

async function precache() {
    const cache = await caches.open(CACHE_NAME);
    // Required: a rejection here fails the install, which is what we want.
    await cache.addAll(SHELL_ASSETS);
    // Best effort: warm what we can, ignore what we cannot.
    await Promise.allSettled(MEDIA_ASSETS.map((path) => cache.add(path)));
}

self.addEventListener('install', (event) => {
    event.waitUntil(precache());
});

// The page sends this once the player has been told an update is ready.
self.addEventListener('message', (event) => {
    if (event.data && event.data.type === 'SKIP_WAITING') self.skipWaiting();
});

self.addEventListener('activate', (event) => {
    event.waitUntil(
        caches.keys().then((keys) =>
            Promise.all(
                keys.filter((key) => key !== CACHE_NAME).map((key) => caches.delete(key)),
            ),
        ),
    );
    self.clients.claim();
});

async function cacheFirst(request) {
    const cached = await caches.match(request);
    if (cached) return cached;
    const response = await fetch(request);
    if (response && response.status === 200) {
        const cache = await caches.open(CACHE_NAME);
        cache.put(request, response.clone());
    }
    return response;
}

async function staleWhileRevalidate(request) {
    const cache = await caches.open(CACHE_NAME);
    const cached = await cache.match(request);
    const network = fetch(request)
        .then((response) => {
            if (response && response.status === 200) {
                cache.put(request, response.clone());
            }
            return response;
        })
        .catch(() => null);
    if (cached) return cached;
    const response = await network;
    if (response) return response;
    // Offline miss: only navigations may fall back to the app shell — code
    // and data requests must fail loudly rather than receive HTML.
    if (request.mode === 'navigate') {
        const shell = await caches.match('./index.html');
        if (shell) return shell;
    }
    return Response.error();
}

self.addEventListener('fetch', (event) => {
    const { request } = event;
    if (request.method !== 'GET') return;
    const url = new URL(request.url);
    if (url.origin !== self.location.origin) return;
    event.respondWith(isMedia(url.pathname) ? cacheFirst(request) : staleWhileRevalidate(request));
});
