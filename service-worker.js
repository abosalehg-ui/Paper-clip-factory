// Caching strategy:
//  - Code & markup (html/css/js/manifest): stale-while-revalidate — served
//    instantly from cache, refreshed in the background, so deployed updates
//    reach returning players on their NEXT visit without manual cache bumps.
//  - Media under assets/ (audio, images, fonts): cache-first — immutable in
//    practice.
// The precache list and cache version below are generated from the actual
// files on disk; CI fails if they drift.
//
// Activation is deliberately NOT immediate. `skipWaiting()` used to run on
// install, so a new worker took over — and deleted the old cache — while an
// open tab was still running the previous build's HTML. Any module that tab
// requested afterwards came back from the new build: two versions of the game
// in one page. The new worker now waits until every tab is gone, or until the
// page explicitly asks it to take over via a SKIP_WAITING message, which the
// page only sends after telling the player to reload.

