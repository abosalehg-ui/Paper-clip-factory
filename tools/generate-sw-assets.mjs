#!/usr/bin/env node
// Regenerates the precache asset list and content-hash cache version inside
// service-worker.js. Run via `npm run build-sw` after adding, removing, or
// changing any shipped file. `--check` exits non-zero if the committed
// service worker is out of date (used by CI), without writing anything.

import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import process from 'node:process';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const SW_PATH = join(ROOT, 'service-worker.js');
const INCLUDE = ['index.html', 'manifest.json', 'css', 'js', 'assets'];

function collectFiles(entry, out) {
    const full = join(ROOT, entry);
    const stats = statSync(full);
    if (stats.isFile()) {
        out.push(entry);
        return;
    }
    for (const child of readdirSync(full).sort()) {
        collectFiles(join(entry, child), out);
    }
}

const files = [];
for (const entry of INCLUDE) collectFiles(entry, files);
files.sort();

const hash = createHash('sha256');
for (const file of files) {
    hash.update(file.replaceAll('\\', '/'));
    hash.update(readFileSync(join(ROOT, file)));
}
const version = hash.digest('hex').slice(0, 8);

const assetLines = ['./', ...files.map((f) => `./${relative('.', f).replaceAll('\\', '/')}`)]
    .map((path) => `    '${path}',`)
    .join('\n');

const START = '// AUTOGEN:START';
const END = '// AUTOGEN:END';
const block = `${START} — generated by tools/generate-sw-assets.mjs (npm run build-sw); do not edit.
const CACHE_VERSION = '${version}';
const ASSETS = [
${assetLines}
];
${END}`;

const source = readFileSync(SW_PATH, 'utf8');
const pattern = new RegExp(`${START}[\\s\\S]*?${END}`);
if (!pattern.test(source)) {
    console.error('AUTOGEN markers not found in service-worker.js');
    process.exit(1);
}
const updated = source.replace(pattern, block);

if (process.argv.includes('--check')) {
    if (updated !== source) {
        console.error(
            'service-worker.js is out of date. Run `npm run build-sw` and commit the result.',
        );
        process.exit(1);
    }
    console.log(`service-worker.js is up to date (cache version ${version}).`);
} else if (updated === source) {
    console.log(`service-worker.js already up to date (cache version ${version}).`);
} else {
    writeFileSync(SW_PATH, updated);
    console.log(`service-worker.js regenerated: ${files.length} assets, cache version ${version}.`);
}
